import { createClient } from 'jsr:@supabase/supabase-js@2'

const corsHeaders = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
}

function buildPrompt(text: string, sourceLanguage: string, targetLanguage: string): string {
  if (sourceLanguage.toLowerCase() === 'kannada') {
    return `You are a translator for NammaConnect, an app helping people communicate across languages in Karnataka.
Translate the following Kannada text into clear, natural everyday ${targetLanguage}.
If translating to Hindi, provide standard conversational Hindi (with Roman transliteration).
If translating to English, provide natural English.

Source text in Kannada: "${text}"

Respond ONLY with a valid JSON object matching this schema, without any markdown formatting or extra commentary:
{
  "translation": "Translated text in ${targetLanguage}",
  "transliteration": "Phonetic pronunciation guide in English Roman alphabet"
}`
  }

  return `You are a translator for NammaConnect, an app helping people communicate across languages in Karnataka.
Translate the following ${sourceLanguage} text into natural, everyday spoken ${targetLanguage} (as commonly spoken in Bengaluru/Karnataka).
Always translate it into authentic, conversational phrasing that locals use in everyday life.
Also provide the phonetic transliteration (pronunciation in Roman script) if the target language is Kannada or Hindi.

Source text: "${text}"

Respond ONLY with a valid JSON object matching this schema, without any markdown formatting or extra commentary:
{
  "translation": "Translated text in ${targetLanguage}",
  "kannada": "Translated text if target is Kannada",
  "transliteration": "Phonetic pronunciation in English Roman letters"
}`
}

async function translateWithGemini(
  text: string,
  sourceLanguage: string,
  targetLanguage: string,
  apiKey: string,
): Promise<{ translation: string; transliteration?: string }> {
  if (sourceLanguage.toLowerCase() === targetLanguage.toLowerCase()) {
    return { translation: text, transliteration: '' }
  }

  const model = Deno.env.get('GEMINI_MODEL') || 'gemini-2.5-flash'
  const prompt = buildPrompt(text, sourceLanguage, targetLanguage)

  const response = await fetch(
    `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${encodeURIComponent(apiKey)}`,
    {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        contents: [
          {
            parts: [{ text: prompt }],
          },
        ],
      }),
    },
  )

  if (!response.ok) {
    const errorText = await response.text().catch(() => '')
    console.error('Gemini API translation error:', response.status, errorText)
    throw new Error(`Translation service returned status ${response.status}`)
  }

  const data = await response.json()
  const rawText = data?.candidates?.[0]?.content?.parts?.[0]?.text?.trim() || ''

  if (!rawText) {
    throw new Error('No translation was generated by Gemini model')
  }

  const cleaned = rawText
    .replace(/^```json\s*/i, '')
    .replace(/^```\s*/i, '')
    .replace(/```$/i, '')
    .trim()

  try {
    const parsed = JSON.parse(cleaned) as {
      translation?: string
      kannada?: string
      transliteration?: string
    }
    const finalTranslation =
      parsed.translation ||
      (targetLanguage.toLowerCase() === 'kannada' ? parsed.kannada : '') ||
      rawText
    return {
      translation: finalTranslation,
      transliteration: parsed.transliteration || '',
    }
  } catch {
    return {
      translation: rawText,
      transliteration: '',
    }
  }
}

Deno.serve(async (req) => {
  if (req.method === 'OPTIONS') {
    return new Response('ok', { headers: corsHeaders })
  }

  try {
    const authHeader = req.headers.get('Authorization')
    if (!authHeader) {
      return new Response(JSON.stringify({ error: 'Missing authorization header' }), {
        status: 401,
        headers: { ...corsHeaders, 'Content-Type': 'application/json' },
      })
    }

    const supabaseUrl = Deno.env.get('SUPABASE_URL') ?? ''
    const supabaseAnonKey = Deno.env.get('SUPABASE_ANON_KEY') ?? ''
    const supabaseServiceKey = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY') ?? ''

    if (!supabaseUrl || !supabaseServiceKey) {
      return new Response(
        JSON.stringify({ error: 'Supabase server environment configuration is missing' }),
        {
          status: 500,
          headers: { ...corsHeaders, 'Content-Type': 'application/json' },
        },
      )
    }

    // Verify caller JWT using user-scoped client
    const userClient = createClient(supabaseUrl, supabaseAnonKey, {
      global: { headers: { Authorization: authHeader } },
    })

    const {
      data: { user },
      error: userError,
    } = await userClient.auth.getUser()

    if (userError || !user) {
      return new Response(
        JSON.stringify({ error: 'Unauthorized: invalid or expired session' }),
        {
          status: 401,
          headers: { ...corsHeaders, 'Content-Type': 'application/json' },
        },
      )
    }

    // Parse and validate payload
    let body: { room_id?: string; text?: string }
    try {
      body = await req.json()
    } catch {
      return new Response(JSON.stringify({ error: 'Invalid JSON request payload' }), {
        status: 400,
        headers: { ...corsHeaders, 'Content-Type': 'application/json' },
      })
    }

    const roomId = body.room_id
    let text = typeof body.text === 'string' ? body.text.trim() : ''

    if (!roomId || !text) {
      return new Response(
        JSON.stringify({ error: 'Both room_id and message text are required' }),
        {
          status: 400,
          headers: { ...corsHeaders, 'Content-Type': 'application/json' },
        },
      )
    }

    // Cap text at 500 chars as instructed
    if (text.length > 500) {
      text = text.slice(0, 500)
    }

    // Service role admin client to bypass RLS and verify room
    const adminClient = createClient(supabaseUrl, supabaseServiceKey)

    const { data: room, error: roomError } = await adminClient
      .from('pair_rooms')
      .select('*')
      .eq('id', roomId)
      .single()

    if (roomError || !room) {
      return new Response(JSON.stringify({ error: 'Room not found or expired' }), {
        status: 404,
        headers: { ...corsHeaders, 'Content-Type': 'application/json' },
      })
    }

    if (room.status !== 'active') {
      return new Response(
        JSON.stringify({ error: 'Room is not currently active' }),
        {
          status: 400,
          headers: { ...corsHeaders, 'Content-Type': 'application/json' },
        },
      )
    }

    // Confirm caller is host or peer
    const isHost = user.id === room.host_id
    const isPeer = user.id === room.peer_id

    if (!isHost && !isPeer) {
      return new Response(
        JSON.stringify({ error: 'User is not an authorized participant in this room' }),
        {
          status: 403,
          headers: { ...corsHeaders, 'Content-Type': 'application/json' },
        },
      )
    }

    const senderRole: 'host' | 'peer' = isHost ? 'host' : 'peer'
    const sourceLanguage: string = isHost ? room.host_language : (room.peer_language || 'Kannada')
    const targetLanguage: string = isHost ? (room.peer_language || 'Kannada') : room.host_language

    let translation = text
    let transliteration: string | null = null

    // If sender language and receiver language are the same, skip Gemini and store translated_text = original_text
    const isSameLanguage =
      sourceLanguage.trim().toLowerCase() === targetLanguage.trim().toLowerCase()

    if (!isSameLanguage) {
      const geminiApiKey = Deno.env.get('GEMINI_API_KEY') || ''
      if (!geminiApiKey) {
        return new Response(
          JSON.stringify({ error: 'GEMINI_API_KEY is not configured on server' }),
          {
            status: 500,
            headers: { ...corsHeaders, 'Content-Type': 'application/json' },
          },
        )
      }

      const result = await translateWithGemini(
        text,
        sourceLanguage,
        targetLanguage,
        geminiApiKey,
      )
      translation = result.translation
      transliteration = result.transliteration || null
    }

    // Insert into pair_messages using service role client
    const { data: insertedMessage, error: insertError } = await adminClient
      .from('pair_messages')
      .insert({
        room_id: roomId,
        sender_id: user.id,
        sender_role: senderRole,
        original_text: text,
        original_language: sourceLanguage,
        translated_text: translation,
        target_language: targetLanguage,
        transliteration: transliteration || null,
      })
      .select()
      .single()

    if (insertError) {
      console.error('Failed to insert pair message:', insertError)
      return new Response(
        JSON.stringify({ error: 'Failed to record message in database' }),
        {
          status: 500,
          headers: { ...corsHeaders, 'Content-Type': 'application/json' },
        },
      )
    }

    return new Response(JSON.stringify({ data: insertedMessage }), {
      status: 200,
      headers: { ...corsHeaders, 'Content-Type': 'application/json' },
    })
  } catch (err: unknown) {
    const message = err instanceof Error ? err.message : 'Internal Server Error'
    console.error('pair-message edge function unhandled error:', err)
    return new Response(JSON.stringify({ error: message }), {
      status: 500,
      headers: { ...corsHeaders, 'Content-Type': 'application/json' },
    })
  }
})
